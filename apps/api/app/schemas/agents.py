"""Wire schemas for the /agents endpoints."""

from __future__ import annotations

from datetime import date
from typing import Annotated, Literal

from pydantic import (
    BaseModel,
    ConfigDict,
    Field,
    StringConstraints,
    ValidationError,
    field_validator,
)


_SUPPORTED_ANALYSTS = {"market", "social", "news", "fundamentals"}
_SUPPORTED_LANGUAGES = {"en-US", "zh-TW", "zh-CN", "ja-JP", "ko-KR", "de-DE"}


class BacktestPair(BaseModel):
    """One historical (symbol, trade_date) input for the backtest harness."""

    symbol: str = Field(..., min_length=1, max_length=20)
    trade_date: date


class BacktestRequest(BaseModel):
    """POST /agents/backtest body.

    Knobs match :class:`RunRequest` so a backtest replicates the exact
    settings a forward run would use. ``horizon_days`` is the realised-
    return window applied uniformly to every pair.
    """

    pairs: list[BacktestPair] = Field(..., min_length=1, max_length=50)
    horizon_days: int = Field(7, ge=1, le=90)
    max_debate_rounds: int = Field(1, ge=1, le=3)
    max_risk_discuss_rounds: int = Field(1, ge=1, le=3)
    deep_thinking: bool = True
    reasoning_effort: Literal["low", "medium", "high", "xhigh", "max"] = "medium"
    response_language: Literal[
        "en-US", "zh-TW", "zh-CN", "ja-JP", "ko-KR", "de-DE"
    ] = "en-US"
    selected_analysts: list[str] = Field(
        default_factory=lambda: ["market", "social", "news", "fundamentals"]
    )

    @field_validator("selected_analysts")
    @classmethod
    def _normalize_analysts(cls, v: list[str]) -> list[str]:
        seen: set[str] = set()
        out: list[str] = []
        for raw in v:
            name = raw.strip().lower()
            if name not in _SUPPORTED_ANALYSTS:
                raise ValueError(
                    f"unknown analyst {raw!r}; supported: {sorted(_SUPPORTED_ANALYSTS)}"
                )
            if name not in seen:
                seen.add(name)
                out.append(name)
        if not out:
            raise ValueError("selected_analysts must contain at least one analyst")
        return out


class OwnerPosition(BaseModel):
    """What the owner holds of the run's symbol. ``unknown`` means the
    accounts could not be read, which is different from holding nothing."""

    model_config = ConfigDict(extra="forbid")

    status: Literal["held", "not_held", "unknown"]
    quantity: float | None = Field(default=None, ge=0)
    market_value: float | None = Field(default=None, ge=0)
    # Currency of ``market_value``; it can differ from the base currency.
    currency: str | None = Field(default=None, max_length=8)
    weight_pct: float | None = Field(default=None, ge=0)
    unrealized_pnl_pct: float | None = None


class OwnerContext(BaseModel):
    """Who the run decides for. Facts only: how the deciding agents must rule
    for this owner is the ``owner_mandate`` prompt, edited in Settings."""

    model_config = ConfigDict(extra="forbid")

    base_currency: str | None = Field(default=None, max_length=8)
    position: OwnerPosition
    # In ``base_currency``.
    investable_total: float | None = Field(default=None, ge=0)
    monthly_contribution: float | None = Field(default=None, ge=0)
    # What the owner asked the chat to remember, in their own words.
    notes: list[Annotated[str, StringConstraints(max_length=240)]] = Field(
        default_factory=list, max_length=30
    )


def owner_context_from_config(raw: object) -> OwnerContext | None:
    """The owner context a run stored when it started, for a resume. A stored
    value that no longer validates resumes the run without one."""
    if raw is None:
        return None
    try:
        return OwnerContext.model_validate(raw)
    except ValidationError:
        return None


class RunRequest(BaseModel):
    """POST /agents/run request body.

    Mirrors TradingAgents' ``TradingAgentsConfig`` knobs — ``max_debate_rounds``,
    ``max_risk_discuss_rounds``, ``reasoning_effort``, ``response_language`` —
    plus our wire fields (``run_id``, ``deep_thinking``).

    Defaults are conservative: shortest debate (1 round each), medium reasoning,
    English. Callers tune up per-run via the Run-cost-estimate UI.

    ``run_id`` is generated by the Nuxt proxy when it INSERTs the
    ``agent_runs`` row and forwarded here so both layers share one canonical id
    — without it the api would mint its own uuid, the run-start event would
    emit that fresh id, and the URL the client persists wouldn't match the row
    in agent_runs (refresh = 404).
    """

    symbol: str = Field(..., min_length=1, max_length=20)
    # Yahoo-resolved company name. The Nuxt proxy resolves and forwards it so
    # the agents anchor on the right company (the "US.MU" → "Munich Re" bug).
    # Optional: direct API callers may omit it; the router then resolves it
    # itself before the graph starts.
    company_name: str | None = Field(default=None, max_length=200)
    trade_date: date | None = None
    max_debate_rounds: int = Field(1, ge=1, le=3)
    max_risk_discuss_rounds: int = Field(1, ge=1, le=3)
    deep_thinking: bool = True
    reasoning_effort: Literal["low", "medium", "high", "xhigh", "max"] = "medium"
    response_language: Literal[
        "en-US", "zh-TW", "zh-CN", "ja-JP", "ko-KR", "de-DE"
    ] = "en-US"
    selected_analysts: list[str] = Field(
        default_factory=lambda: ["market", "social", "news", "fundamentals"]
    )
    run_id: str | None = Field(default=None, min_length=1, max_length=64)
    # Built by the Nuxt proxy from the owner's accounts. Without it the run
    # decides for no one in particular, as a backtest does.
    owner_context: OwnerContext | None = None

    @field_validator("selected_analysts")
    @classmethod
    def _normalize_analysts(cls, v: list[str]) -> list[str]:
        # Accept any case, dedupe in input order, reject unknowns. Empty list
        # means "use the full default" — the agents pipeline must run at
        # least one analyst.
        seen: set[str] = set()
        out: list[str] = []
        for raw in v:
            name = raw.strip().lower()
            if name not in _SUPPORTED_ANALYSTS:
                raise ValueError(
                    f"unknown analyst {raw!r}; supported: {sorted(_SUPPORTED_ANALYSTS)}"
                )
            if name not in seen:
                seen.add(name)
                out.append(name)
        if not out:
            raise ValueError("selected_analysts must contain at least one analyst")
        return out
